// Regenerates the performance tables in the spec (between the perf-tables markers of
// docs/SPEC.md) from bench/results/{rust,rust-mem,js}.json.

import fs from "node:fs";
import path from "node:path";

type Messages = { replies: number; offers: number; answers: number; removed: number; bytes?: number };
type Scenario = { name: string; ops: number; median_ns_per_op: number; min_ns_per_op: number; messages: Messages };
type Memory = { name: string; memberships: number; bytes_per_membership: number; rss_bytes_per_membership?: number };
type Scaling = { mode: string; threads: number; ops_per_sec: number };
type Results = { env?: Record<string, unknown>; scenarios?: Scenario[]; memory?: Memory[]; scaling?: Scaling[] };

const dir = path.join(import.meta.dirname, "results");
const read = (f: string): Results => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const rust = read("rust.json");
const rustMem = read("rust-mem.json");
const js = read("js.json");

const f1 = (n: number) => n.toFixed(1);
const f2 = (n: number) => n.toFixed(2);
const sameMessages = (a: Messages, b: Messages) =>
  a.replies === b.replies && a.offers === b.offers && a.answers === b.answers && a.removed === b.removed && (a.bytes ?? 0) === (b.bytes ?? 0);

const lines: string[] = [];
lines.push(`- Generated by \`bench/run.sh\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`);
lines.push(`- Rust: ${JSON.stringify(rust.env)}`);
lines.push(`- JS: ${JSON.stringify(js.env)}`);
lines.push("- Median of 5 runs after 2 warmups. 10 offers per announce, numwant 10. Core scenarios count messages without serializing; `proto_*` / `pipeline_*` include JSON parsing and serialization (1.3 KB SDP per offer, ~14 KB per announce frame) and compare output bytes.");
lines.push("- Rust scenarios without a suffix use the default `RandomSample`; `_window` / `_round_robin` use the other strategies (JS always uses a random window). `_serde_json` / `_sonic` are the two `wt-proto` parser backends; JS uses `StringDecoder` + `JSON.parse` / `JSON.stringify` like uws-tracker.", "");

lines.push("### Time per operation", "");
lines.push("| Scenario | Ops/run | JS ns/op | Rust ns/op | Speedup | Same messages |");
lines.push("|---|---:|---:|---:|---:|:-:|");
for (const r of rust.scenarios!) {
  const twin = r.name.replace(/_(window|round_robin|serde_json|sonic)$/, "");
  const j = js.scenarios!.find((s) => s.name === twin);
  if (!j) continue;
  const label = twin === r.name ? r.name : `${r.name} (vs JS ${twin})`;
  // Strategy variants send to different peers; parser backends must match exactly.
  const comparable = r.name === twin || /_(serde_json|sonic)$/.test(r.name);
  const same = comparable ? (sameMessages(r.messages, j.messages) ? "yes" : "**no**") : "n/a";
  lines.push(
    `| ${label} | ${r.ops.toLocaleString("en-US")} | ${f1(j.median_ns_per_op)} | ${f1(r.median_ns_per_op)} | ${f1(j.median_ns_per_op / r.median_ns_per_op)}× | ${same} |`,
  );
}

lines.push("", "### Memory per membership (peer-in-swarm)", "");
lines.push("| State | Memberships | JS heapUsed B | Rust heap B (incl. Vec slack) | Rust RSS B |");
lines.push("|---|---:|---:|---:|---:|");
for (const r of rustMem.memory!) {
  const j = js.memory!.find((m) => m.name === r.name)!;
  lines.push(
    `| ${r.name} | ${r.memberships.toLocaleString("en-US")} | ${f1(j.bytes_per_membership)} | ${f1(r.bytes_per_membership)} | ${f1(r.rss_bytes_per_membership!)} |`,
  );
}

lines.push("", "### Multi-core scaling (re-announce, M announces/s)", "");
lines.push("Strong: one 600k-membership state split across N shards by `swarm % N`. Weak: every shard holds a full copy.", "");
lines.push("| Threads | JS strong | Rust strong | Rust/JS | JS weak | Rust weak |");
lines.push("|---:|---:|---:|---:|---:|---:|");
const pick = (r: Results, mode: string, threads: number) =>
  r.scaling!.find((s) => s.mode === mode && s.threads === threads)!.ops_per_sec;
const threadCounts = [...new Set(rust.scaling!.map((s) => s.threads))];
for (const t of threadCounts) {
  const [js1s, rs1s, js1w, rs1w] = [pick(js, "strong", 1), pick(rust, "strong", 1), pick(js, "weak", 1), pick(rust, "weak", 1)];
  const [jss, rss, jsw, rsw] = [pick(js, "strong", t), pick(rust, "strong", t), pick(js, "weak", t), pick(rust, "weak", t)];
  lines.push(
    `| ${t} | ${f2(jss / 1e6)} (${f1(jss / js1s)}×) | ${f2(rss / 1e6)} (${f1(rss / rs1s)}×) | ${f1(rss / jss)}× | ${f2(jsw / 1e6)} (${f1(jsw / js1w)}×) | ${f2(rsw / 1e6)} (${f1(rsw / rs1w)}×) |`,
  );
}

// Load test (loadtest/run.sh), if it has been run.
const loadFile = path.join(dir, "load.json");
if (fs.existsSync(loadFile)) {
  type Run = {
    label: string; conns: number; connected: number; failed: number; closed_early: number;
    per_second: { sent: number; received: number };
    rtt_ms: { p50: number; p99: number };
    server: { cpu_cores: number; cpu_us_per_message: number; rss_bytes: number; rss_bytes_per_conn: number } | null;
  };
  const load = JSON.parse(fs.readFileSync(loadFile, "utf8")) as { env: Record<string, unknown>; smoke_same: boolean; runs: Run[] };
  const r0 = load.runs[0] as unknown as { swarms: number; offers: number; duration_s: number };
  lines.push("", "### Load test (end to end, `loadtest/run.sh`)", "");
  lines.push(`- ${JSON.stringify(load.env)}; client and server on the same machine.`);
  lines.push(`- ${r0?.swarms} swarms, ${r0?.offers} offers per announce (1.3 KB SDP), every offer answered, ${Math.round(r0?.duration_s ?? 0)} s steady phase. JS with \`compression: 0\` (Rust does not negotiate permessage-deflate). \`js-workers\` = JS multi-worker tracker, \`rust-1\` / \`rust-n\` = 1 / all-core workers.`);
  lines.push(`- Wire smoke check (same messages from JS and Rust): **${load.smoke_same ? "yes" : "no"}**.`, "");
  lines.push("| Profile / target | Conns (connected) | Announce every | Errors | Msgs/s (in + out) | Server CPU (cores) | CPU µs / msg | RSS MiB | RSS KiB / conn | RTT p50 / p99 ms |");
  lines.push("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
  const order = (l: string) => (l.startsWith("light") ? 0 : 1);
  for (const r of [...load.runs].sort((a, b) => order(a.label) - order(b.label) || (a.label < b.label ? -1 : 1))) {
    const s = r.server;
    const interval = (r as unknown as { interval_s: number }).interval_s;
    lines.push(
      `| ${r.label} | ${r.conns} (${r.connected}) | ${interval} s | ${r.failed + r.closed_early} | ${Math.round(r.per_second.sent + r.per_second.received).toLocaleString("en-US")} | ${s ? f2(s.cpu_cores) : "?"} | ${s ? f1(s.cpu_us_per_message) : "?"} | ${s ? f1(s.rss_bytes / 2 ** 20) : "?"} | ${s ? f1(s.rss_bytes_per_conn / 1024) : "?"} | ${f2(r.rtt_ms.p50)} / ${f2(r.rtt_ms.p99)} |`,
    );
  }
}

const tables = lines.join("\n");
const specPath = path.join(import.meta.dirname, "../docs/SPEC.md");
const BEGIN = "<!-- perf-tables:begin -->";
const END = "<!-- perf-tables:end -->";
const spec = fs.readFileSync(specPath, "utf8");
const [b, e] = [spec.indexOf(BEGIN), spec.indexOf(END)];
if (b < 0 || e < b) throw new Error(`perf-tables markers not found in ${specPath}`);
fs.writeFileSync(specPath, spec.slice(0, b + BEGIN.length) + "\n" + tables + "\n" + spec.slice(e));
process.stdout.write(tables + "\n");
